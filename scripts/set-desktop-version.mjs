#!/usr/bin/env node
/**
 * 仅同步桌面端版本号（不改根 npm 包 / TUI）。
 *
 * 覆盖：
 *   - desktop/package.json
 *   - desktop/src-tauri/tauri.conf.json
 *   - desktop/src-tauri/Cargo.toml
 *   - web/src/generated/desktopVersion.ts（给设置页 / 更新检查用）
 *   - web/public/desktop-version.json
 *
 * 用法：node scripts/set-desktop-version.mjs 0.0.1-beta
 * Tag 约定：desktop-app-v${version}  →  desktop-app-v0.0.1-beta
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const TAG_PREFIX = 'desktop-app-v'

const version = (process.argv[2] || '').trim().replace(/^v/, '')
if (!version) {
  console.error('用法: node scripts/set-desktop-version.mjs <version>')
  process.exit(1)
}
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`非法版本号: ${version}`)
  process.exit(1)
}

function setJsonVersion(relPath) {
  const p = join(root, relPath)
  if (!existsSync(p)) {
    console.warn(`[skip] 不存在: ${relPath}`)
    return
  }
  const json = JSON.parse(readFileSync(p, 'utf8'))
  json.version = version
  writeFileSync(p, `${JSON.stringify(json, null, 2)}\n`)
  console.log(`[ok] ${relPath} -> ${version}`)
}

function setCargoVersion(relPath) {
  const p = join(root, relPath)
  if (!existsSync(p)) {
    console.warn(`[skip] 不存在: ${relPath}`)
    return
  }
  const src = readFileSync(p, 'utf8')
  let inPackage = false
  let replaced = false
  const out = src
    .split('\n')
    .map((line) => {
      if (/^\s*\[[^\]]+\]\s*$/.test(line)) {
        inPackage = /^\s*\[package\]\s*$/.test(line)
        return line
      }
      if (inPackage && !replaced && /^\s*version\s*=/.test(line)) {
        replaced = true
        return `version = "${version}"`
      }
      return line
    })
    .join('\n')
  writeFileSync(p, out)
  console.log(`[ok] ${relPath} -> ${version}`)
}

function writeWebArtifacts() {
  const tag = `${TAG_PREFIX}${version}`
  const genDir = join(root, 'web/src/generated')
  mkdirSync(genDir, { recursive: true })
  const ts = `/* auto-generated by scripts/set-desktop-version.mjs — do not edit */
export const DESKTOP_VERSION = ${JSON.stringify(version)}
export const DESKTOP_TAG_PREFIX = ${JSON.stringify(TAG_PREFIX)}
export const DESKTOP_RELEASE_TAG = ${JSON.stringify(tag)}
export const GITHUB_REPO = 'iammm0/secbot'
`
  writeFileSync(join(genDir, 'desktopVersion.ts'), ts)
  console.log(`[ok] web/src/generated/desktopVersion.ts -> ${version}`)

  const pub = {
    version,
    tagPrefix: TAG_PREFIX,
    releaseTag: tag,
    githubRepo: 'iammm0/secbot',
  }
  writeFileSync(join(root, 'web/public/desktop-version.json'), `${JSON.stringify(pub, null, 2)}\n`)
  console.log(`[ok] web/public/desktop-version.json -> ${version}`)
}

function updateReadmeExamples() {
  const tag = `${TAG_PREFIX}${version}`
  const tagRe = /desktop-app-v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?/g
  for (const rel of ['README.md', 'README_CN.md', 'README_EN.md']) {
    const p = join(root, rel)
    if (!existsSync(p)) continue
    const src = readFileSync(p, 'utf8')
    const out = src.replace(tagRe, tag)
    if (out === src) {
      console.warn(`[skip] ${rel} 中没有 desktop-app-v* 示例`)
      continue
    }
    writeFileSync(p, out)
    console.log(`[ok] ${rel} -> ${tag}`)
  }
}

setJsonVersion('desktop/package.json')
setJsonVersion('desktop/src-tauri/tauri.conf.json')
setCargoVersion('desktop/src-tauri/Cargo.toml')
writeWebArtifacts()
updateReadmeExamples()

console.log(`\n桌面端版本已设置为 ${version}`)
console.log(`对应 Git 标签: ${TAG_PREFIX}${version}`)

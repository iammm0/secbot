/**
 * 版本号同步脚本的共享工具（scripts/set-release-version.mjs 与
 * scripts/set-desktop-version.mjs 共用），避免两个脚本各自维护
 * 桌面/web 版本文件导致漏改。
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

export const TAG_PREFIX = 'desktop-app-v';
export const GITHUB_REPO = 'iammm0/secbot';

export function setJsonVersion(root, relPath, version) {
  const p = join(root, relPath);
  if (!existsSync(p)) {
    console.warn(`[skip] 不存在: ${relPath}`);
    return;
  }
  const src = readFileSync(p, 'utf8');
  const json = JSON.parse(src);
  // 只替换顶层 version 字段，保留原文件其余格式（如紧凑数组），避免无意义 diff
  const out = src.replace(
    `"version": ${JSON.stringify(json.version)}`,
    `"version": ${JSON.stringify(version)}`,
  );
  if (out === src) {
    if (json.version === version) {
      console.log(`[skip] ${relPath} 已是 ${version}`);
    } else {
      console.warn(`[warn] 未在 ${relPath} 找到 version 字段`);
    }
    return;
  }
  writeFileSync(p, out);
  console.log(`[ok] ${relPath} -> ${version}`);
}

export function setCargoVersion(root, relPath, version) {
  const p = join(root, relPath);
  if (!existsSync(p)) {
    console.warn(`[skip] 不存在: ${relPath}`);
    return;
  }
  const src = readFileSync(p, 'utf8');
  // 仅替换 [package] 段内的首个 version = "..."
  let inPackage = false;
  let replaced = false;
  const out = src
    .split('\n')
    .map((line) => {
      if (/^\s*\[[^\]]+\]\s*$/.test(line)) {
        inPackage = /^\s*\[package\]\s*$/.test(line);
        return line;
      }
      if (inPackage && !replaced && /^\s*version\s*=/.test(line)) {
        replaced = true;
        return `version = "${version}"`;
      }
      return line;
    })
    .join('\n');
  if (!replaced) {
    console.warn(`[warn] 未在 [package] 段找到 version: ${relPath}`);
  }
  writeFileSync(p, out);
  console.log(`[ok] ${relPath} -> ${version}`);
}

/** 重新生成 web 的桌面版本产物（更新检查/设置页用） */
export function writeWebArtifacts(root, version) {
  const tag = `${TAG_PREFIX}${version}`;
  const genDir = join(root, 'web/src/generated');
  mkdirSync(genDir, { recursive: true });
  const ts = `/* auto-generated by scripts/lib/set-version-common.mjs — do not edit */
export const DESKTOP_VERSION = ${JSON.stringify(version)}
export const DESKTOP_TAG_PREFIX = ${JSON.stringify(TAG_PREFIX)}
export const DESKTOP_RELEASE_TAG = ${JSON.stringify(tag)}
export const GITHUB_REPO = 'iammm0/secbot'
`;
  writeFileSync(join(genDir, 'desktopVersion.ts'), ts);
  console.log(`[ok] web/src/generated/desktopVersion.ts -> ${version}`);

  const pub = {
    version,
    tagPrefix: TAG_PREFIX,
    releaseTag: tag,
    githubRepo: GITHUB_REPO,
  };
  writeFileSync(
    join(root, 'web/public/desktop-version.json'),
    `${JSON.stringify(pub, null, 2)}\n`,
  );
  console.log(`[ok] web/public/desktop-version.json -> ${version}`);
}

/** 同步 README 中的 desktop-app-v* 示例标签 */
export function updateReadmeExamples(root, version) {
  const tag = `${TAG_PREFIX}${version}`;
  const tagRe = /desktop-app-v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?/g;
  for (const rel of ['README.md', 'README_CN.md', 'README_EN.md']) {
    const p = join(root, rel);
    if (!existsSync(p)) continue;
    const src = readFileSync(p, 'utf8');
    const out = src.replace(tagRe, tag);
    if (out === src) {
      console.warn(`[skip] ${rel} 中没有 desktop-app-v* 示例`);
      continue;
    }
    writeFileSync(p, out);
    console.log(`[ok] ${rel} -> ${tag}`);
  }
}
